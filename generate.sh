#!/bin/bash
cd "$(dirname "$0")"
source ./script/setup.sh

export XCODEGEN_AIRLOCK_CODE_SIGN_IDENTITY="airlock-codesign-certificate"
build_version="$(cat VERSION)"
generate_xcodeproj=1
generate_cmd_help=1
generate_shell_parser=1
generate_git_hash=0
mark_dirty=0
while test $# -gt 0; do
    case $1 in
        --build-version) build_version="$2"; shift 2 ;;
        --codesign-identity) XCODEGEN_AIRLOCK_CODE_SIGN_IDENTITY="$2"; shift 2 ;;
        --generate-git-hash) generate_git_hash=1; shift 1;;
        --mark-dirty) mark_dirty=1; shift 1;;
        --ignore-cmd-help) generate_cmd_help=0; shift 1 ;;
        --ignore-xcodeproj) generate_xcodeproj=0; shift 1 ;;
        --ignore-shell-parser) generate_shell_parser=0; shift 1 ;;
        *) echo "Unknown option $1"; exit 1 ;;
    esac
done

# Capture provenance before generation itself modifies tracked files.
git_hash=SNAPSHOT
git_short_hash=SNAPSHOT
if test $generate_git_hash = 1; then
    git_hash="$(git rev-parse HEAD)"
    git_short_hash="$(git rev-parse --short HEAD)"
    if test $mark_dirty = 1 && test -n "$(git status --porcelain)"; then
        git_hash="$git_hash-dirty"
        git_short_hash="$git_short_hash-dirty"
    fi
fi

if test $generate_shell_parser = 1; then
    ./generate-shell-parser.sh
fi

if test $generate_cmd_help = 1; then
    # It takes 300ms for the script to complete
    ./script/generate-cmd-help.sh
fi

cat > Sources/Common/versionGenerated.swift <<EOF
// FILE IS GENERATED BY generate.sh
public let airlockAppVersion = "$build_version"
EOF

entries() {
    for file in docs/airlock-*.adoc; do
        if grep -q 'exec-and-forget' <<< $file; then
            continue
        fi
        subcommand=$(basename $file | sed 's/^airlock-//' | sed 's/\.adoc$//')
        desc="$(grep :manpurpose: "$file" | sed -E 's/:manpurpose: //')"
        echo "    [\"  $subcommand\", \"$desc\"],"
    done
}

cat <<EOF > ./Sources/Cli/subcommandDescriptionsGenerated.swift
// FILE IS GENERATED FROM docs/airlock-*.adoc files
// TO REGENERATE THE FILE RUN generate.sh

let subcommandDescriptions = [
$(entries)
]
EOF

cat <<EOF > ./Sources/Common/gitHashGenerated.swift
// FILE IS GENERATED BY generate.sh
public let gitHash = "$git_hash"
public let gitShortHash = "$git_short_hash"
EOF

if test $generate_xcodeproj = 1; then
    export XCODEGEN_AIRLOCK_VERSION=$build_version
    ./script/install-dep.sh --xcodegen
    ./.deps/xcodegen/xcodegen # https://github.com/yonaskolb/XcodeGen
fi
